# ---------------------------------------------------------------------------
class Macros:
    def __init__(self) -> None:
        self.v: dict[str, str] = {}

    def set(self, key: str, value, fmt: str | None = None) -> str:
        if isinstance(value, str):
            s = value
        elif value is None or (isinstance(value, float) and not math.isfinite(value)):
            s = "--"
        elif fmt is not None:
            s = format(value, fmt)
        elif isinstance(value, (int, np.integer)):
            s = f"{int(value):,}".replace(",", "{,}")
        else:
            s = f"{value:.3f}"
        if re.match(r"^-\d", s):
            s = "$-$" + s[1:]
        self.v[key] = s
        return s

    def tex(self) -> str:
        lines = ["% generated by build_paper3.py -- do not edit"]
        for k, s in sorted(self.v.items()):
            lines.append(r"\expandafter\def\csname val@" + k + r"\endcsname{" + s + "}")
        return "\n".join(lines) + "\n"


M = Macros()


def pct(x: float, nd: int = 1) -> str:
    return f"{100 * x:.{nd}f}"


def fmt_p(p: float) -> str:
    if p < 1e-4:
        return r"$<10^{-4}$"
    return f"${p:.4f}$" if p < 0.01 else f"${p:.3f}$"


def write(name: str, text: str) -> None:
    # typographic minus for negative numbers in table cells and intervals
    text = re.sub(r"(?<=[&,] )-(?=\d)", "$-$", text)
    text = re.sub(r"(?<=\[)-(?=\d)", "$-$", text)
    (GEN / name).write_text(text)


def rank_marks(values: dict, lower_better: bool = True, nd: int = 1) -> dict:
    """Bold for the best, underline for the second best, compared at the
    displayed precision (ties share the mark)."""
    shown = {k: round(v, nd) for k, v in values.items() if v is not None and np.isfinite(v)}
    uniq = sorted(set(shown.values()), reverse=not lower_better)
    out = {}
    for k, v in values.items():
        if v is None or not np.isfinite(v):
            out[k] = "--"
            continue
        s = f"{v:.{nd}f}"
        if uniq and round(v, nd) == uniq[0]:
            s = r"\best{" + s + "}"
        elif len(uniq) > 1 and round(v, nd) == uniq[1]:
            s = r"\second{" + s + "}"
        out[k] = s
    return out


